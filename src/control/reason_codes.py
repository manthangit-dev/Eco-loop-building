    NATIVE = "NATIVE"
    OCCUPIED_NORMAL = "OCCUPIED_NORMAL"
    OCCUPIED_RECOVERY = "OCCUPIED_RECOVERY"
    VACANCY_GRACE = "VACANCY_GRACE"
    UNOCCUPIED_RELAXED = "UNOCCUPIED_RELAXED"
    HOLD = "HOLD"
    FAILSAFE_RESET = "FAILSAFE_RESET"
    DISABLED = "DISABLED"


