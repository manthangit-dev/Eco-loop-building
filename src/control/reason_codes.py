    HOLD_CURRENT_COMMAND = "HOLD_CURRENT_COMMAND"
    APPLY_OCCUPIED_NORMAL = "APPLY_OCCUPIED_NORMAL"
    APPLY_OCCUPIED_RECOVERY = "APPLY_OCCUPIED_RECOVERY"
    APPLY_UNOCCUPIED_RELAXATION = "APPLY_UNOCCUPIED_RELAXATION"
