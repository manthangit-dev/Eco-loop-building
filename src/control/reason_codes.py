    REJECT_MISSING_DATA = "REJECT_MISSING_DATA"
    REJECT_STALE_STATE = "REJECT_STALE_STATE"
    REJECT_INVALID_SEQUENCE = "REJECT_INVALID_SEQUENCE"
    REJECT_PLENUM = "REJECT_PLENUM"
    REJECT_UNAPPROVED_ZONE = "REJECT_UNAPPROVED_ZONE"
    REJECT_OUT_OF_BOUNDS = "REJECT_OUT_OF_BOUNDS"
    TEMPERATURE_PROTECTION = "TEMPERATURE_PROTECTION"
    VACANCY_GRACE = "VACANCY_GRACE"
    DISABLED = "DISABLED"


